local function refreshBlipStatus()
	for _,blip in ipairs(getElementsByType("blip"))do
		if(isElement(blip))then
			local icon = getBlipIcon(blip)
			BlipStatus[icon] = true
			if(BlipCategoryStatus[icon] == nil)then
				BlipCategoryStatus[icon] = true
			end
		end
	end
end
refreshBlipStatus()

function BliplegendRender()
	if(getElementData(localPlayer,"redfieldClick") ~= true and isPlayerMapVisible())then
		Rendered = true
		local x,y = guiGetScreenSize()
		local baseX,baseY = 1179 * (x / 1440),4
		local position = 0
		local language = getElementData(localPlayer,"Language") or 1
		if(not Bliplegend[language])then language = 1 end
		for i,v in ipairs(Bliplegend[language])do
			if(BlipStatus[v[2]] == true)then
				position = position + 1
				local offsetY = baseY + (position - 1) * 20 * (y / 900)
				local iconSize = 16 * (x / 1440)
				local textOffsetX = 22 * (x / 1440)
				local alpha = 255
				if(BlipCategoryStatus[v[2]] == false)then alpha = 125 end
				dxDrawImage(baseX,offsetY,iconSize,iconSize,"Images/Blips/"..v[2]..".png",0,0,0,tocolor(255,255,255,alpha),false)
				dxDrawText(v[1],baseX+textOffsetX+1,offsetY+1,baseX+textOffsetX+250,offsetY+iconSize,tocolor(0,0,0,alpha),0.9*(x/1440),"default-bold","left","center",false,false,false,false,false)
				dxDrawText(v[1],baseX+textOffsetX,offsetY,baseX+textOffsetX+250,offsetY+iconSize,tocolor(255,255,255,alpha),0.9*(x/1440),"default-bold","left","center",false,false,false,false,false)
			end
		end
	else
		Rendered = false
	end
end
addEventHandler("onClientRender",root,BliplegendRender)

function toggleBlipCategoryClick(mouseX,mouseY)
	local x,y = guiGetScreenSize()
	local baseX,baseY = 1179 * (x / 1440),4
	local position = 0
	local language = getElementData(localPlayer,"Language") or 1
	if(not Bliplegend[language])then language = 1 end
	for i,v in ipairs(Bliplegend[language])do
		if(BlipStatus[v[2]] == true)then
			position = position + 1
			local offsetY = baseY + (position - 1) * 20 * (y / 900)
			local iconSize = 16 * (x / 1440)
			local textOffsetX = 22 * (x / 1440)
			if(mouseX >= baseX and mouseX <= baseX+textOffsetX+250 and mouseY >= offsetY and mouseY <= offsetY+iconSize)then
				if(BlipCategoryStatus[v[2]] ~= false)then
					SaveBlipsTemporary[v[2]] = {}
					for _,blip in ipairs(getElementsByType("blip"))do
						if(isElement(blip) and getBlipIcon(blip) == v[2])then
							local bx,by,bz = getElementPosition(blip)
							local size = getBlipSize(blip)
							local r,g,b,a = getBlipColor(blip)
							local ordering = getBlipOrdering(blip)
							local visibleDistance = getBlipVisibleDistance(blip)
							table.insert(SaveBlipsTemporary[v[2]],{bx,by,bz,v[2],size,r,g,b,a,ordering,visibleDistance})
							destroyElement(blip)
						end
					end
					BlipCategoryStatus[v[2]] = false
				else
					for _,blip in ipairs(SaveBlipsTemporary[v[2]] or {})do
						createBlip(blip[1],blip[2],blip[3],blip[4],blip[5],blip[6],blip[7],blip[8],blip[9],blip[10],blip[11])
					end
					BlipCategoryStatus[v[2]] = true
				end
				break
			end
		end
	end
end

